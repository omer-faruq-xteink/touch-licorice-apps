"""Bundle a gamekit game: tools/gamekit/gamekit.lua + the app's src/*.lua -> the app's index.lua.

  python tools/gamekit/bundle.py apps/<game>

The device has no `require` for package files, so the kit becomes `local kit = (function() ... end)()`
at the top, then the shared kit modules an app asks for (`shared`: tools/gamekit/<name>.lua, such
as cards) and any other src/*.lua module (alphabetical, except main.lua), each a module function
reachable with `require('<name>')`, then src/main.lua. An app's own bundle.py calls this, and
build_all.py runs that before packing.
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KIT = os.path.join(ROOT, 'tools', 'gamekit', 'gamekit.lua')


def bundle(app_dir, shared=()):
    name = os.path.basename(os.path.normpath(app_dir))
    src = os.path.join(app_dir, 'src')
    kit_dir = os.path.dirname(KIT)
    parts = [f"-- GENERATED by tools/gamekit/bundle.py from tools/gamekit/gamekit.lua and apps/{name}/src/\n"
             "-- -- edit those files, not this one.\n",
             "local kit = (function()\n" + open(KIT, encoding='utf-8').read().rstrip('\n') + "\nend)()\n"]
    mods = [os.path.join(kit_dir, n + '.lua') for n in shared]
    mods += [os.path.join(src, f) for f in sorted(os.listdir(src)) if f.endswith('.lua') and f != 'main.lua']
    if mods:
        parts.append("""
local __mods, __loaded = {}, {}
local function require(n)
  local v = __loaded[n]
  if v ~= nil then return v end
  local f = __mods[n]
  if not f then error('module not found: ' .. tostring(n)) end
  v = f()
  if v == nil then v = true end
  __loaded[n] = v
  return v
end
""")
        for path in mods:
            body = open(path, encoding='utf-8').read().rstrip('\n')
            parts.append(f"\n__mods['{os.path.basename(path)[:-4]}'] = function()\n{body}\nend\n")
    parts.append('\n' + open(os.path.join(src, 'main.lua'), encoding='utf-8').read())
    text = ''.join(parts)
    out = os.path.join(app_dir, 'index.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'{name}: index.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle(sys.argv[1])
