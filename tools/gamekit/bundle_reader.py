"""Bundle a reading app (RSS, Instapaper, Readwise, wallabag): its src/main.lua, with the other
src/*.lua and the shared AI modules (tools/gamekit/ai.lua, aiui.lua) as modules main reaches with
require('<name>'), since the device has no require for package files. Each package gets its own
copy of the shared modules: no app needs another installed.

  python tools/gamekit/bundle_reader.py apps/<app>     (an app's own bundle.py calls this)
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHARED = ('ai', 'aiui')

LOADER = """
local __mods, __loaded = {}, {}
local function require(n)
  local v = __loaded[n]
  if v ~= nil then return v end
  local f = __mods[n]
  if not f then error('module not found: ' .. tostring(n)) end
  v = f()
  if v == nil then v = true end
  __loaded[n] = v
  return v
end
"""


def bundle(app_dir):
    name = os.path.basename(os.path.normpath(app_dir))
    src = os.path.join(app_dir, 'src')
    parts = [f"-- GENERATED by tools/gamekit/bundle_reader.py from apps/{name}/src/ and tools/gamekit/ai.lua, aiui.lua\n"
             "-- -- edit those files, not this one.\n", LOADER]
    paths = [os.path.join(ROOT, 'tools', 'gamekit', n + '.lua') for n in SHARED]
    paths += [os.path.join(src, f) for f in sorted(os.listdir(src)) if f.endswith('.lua') and f != 'main.lua']
    for path in paths:
        body = open(path, encoding='utf-8').read().rstrip('\n')
        parts.append(f"\n__mods['{os.path.basename(path)[:-4]}'] = function()\n{body}\nend\n")
    parts.append('\n' + open(os.path.join(src, 'main.lua'), encoding='utf-8').read())
    text = ''.join(parts)
    out = os.path.join(app_dir, 'index.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'{name}: index.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle(sys.argv[1])
