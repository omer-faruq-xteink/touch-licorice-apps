"""Write site/assets/unescape.js: Python's html.unescape in JavaScript, with the same HTML5 entity
table and the same rules for broken references, so the web converters turn HTML into exactly the
text apkg2cards.py and stardict2shards.py make.

  python -I tools/make_unescape_js.py
"""
import html, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'site', 'assets', 'unescape.js')

ents = html.entities.html5
invalid_refs = {str(k): v for k, v in html._invalid_charrefs.items()}
invalid_cps = sorted(html._invalid_codepoints)

js = f"""// GENERATED by tools/make_unescape_js.py from Python's html module: do not edit.
// unescapeHtml(s) is Python's html.unescape(s): the same entities and the same handling of
// references without ";" and of invalid numbers.

const ENT = {json.dumps(ents, ensure_ascii=True, separators=(',', ':'))};
const BAD_REF = {json.dumps(invalid_refs, ensure_ascii=True, separators=(',', ':'))};
const BAD_CP = new Set({json.dumps(invalid_cps, separators=(',', ':'))});
const RE = /&(#[0-9]+;?|#[xX][0-9a-fA-F]+;?|[^\\t\\n\\f <&#;]{{1,32}};?)/g;

function ref(s) {{
  if (s[0] === '#') {{
    const n = s[1] === 'x' || s[1] === 'X' ? parseInt(s.slice(2).replace(/;$/, ''), 16) : parseInt(s.slice(1).replace(/;$/, ''), 10);
    if (Object.prototype.hasOwnProperty.call(BAD_REF, n)) return BAD_REF[n];
    if ((n >= 0xD800 && n <= 0xDFFF) || n > 0x10FFFF) return '\\uFFFD';
    if (BAD_CP.has(n)) return '';
    return String.fromCodePoint(n);
  }}
  if (Object.prototype.hasOwnProperty.call(ENT, s)) return ENT[s];
  for (let x = s.length - 1; x > 1; x--) {{
    if (Object.prototype.hasOwnProperty.call(ENT, s.slice(0, x))) return ENT[s.slice(0, x)] + s.slice(x);
  }}
  return '&' + s;
}}

export function unescapeHtml(s) {{
  if (!s.includes('&')) return s;
  return s.replace(RE, (m, g) => ref(g));
}}
"""
open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
print(f'{OUT}: {len(ents)} entities, {len(js) // 1024} KB')
