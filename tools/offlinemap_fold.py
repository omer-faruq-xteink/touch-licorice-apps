"""Write the name-folding table of the Offline Map tool and app from one rule, so both fold alike:
site/tools/offlinemap/fold.js and apps/offlinemap/src/fold.lua.

  python -I tools/offlinemap_fold.py

The rule (checked by site/test/fixtures/fold_words.tsv on both sides): ASCII A-Z to lowercase; Latin
letters in U+00C0-U+024F and U+1E00-U+1EFF to their base letters in lowercase (with the specials
below); Greek without accents, lowercase, final sigma as sigma; Cyrillic lowercase. Whitespace and
- _ . , ' ’ ( ) / become one space, and the result is trimmed. Everything else is kept.
"""
import json, os, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPECIAL = {'ß': 'ss', 'ẞ': 'ss', 'æ': 'ae', 'Æ': 'ae', 'œ': 'oe', 'Œ': 'oe', 'ø': 'o', 'Ø': 'o', 'đ': 'd', 'Đ': 'd',
           'ł': 'l', 'Ł': 'l', 'ı': 'i', 'İ': 'i', 'þ': 'th', 'Þ': 'th', 'ð': 'd', 'Ð': 'd', 'ħ': 'h', 'Ħ': 'h',
           'ŧ': 't', 'Ŧ': 't', 'ŋ': 'ng', 'Ŋ': 'ng', 'ĸ': 'k', 'ſ': 's', 'ŀ': 'l', 'Ŀ': 'l', 'ƒ': 'f'}
SEP = " \t\n\r-_.,'’()/"


def strip(ch):
    return ''.join(c for c in unicodedata.normalize('NFD', ch) if unicodedata.category(c) != 'Mn').lower()


def table():
    t = {}
    for cp in list(range(0xC0, 0x250)) + list(range(0x1E00, 0x1F00)):
        ch = chr(cp)
        if unicodedata.category(ch)[0] != 'L':
            continue
        if ch in SPECIAL:
            f = SPECIAL[ch]
        else:
            d = strip(ch)
            f = d if d and d.isascii() else ch.lower()
        if f != ch:
            t[ch] = f
    for cp in range(0x370, 0x400):
        ch = chr(cp)
        if unicodedata.category(ch)[0] != 'L':
            continue
        d = strip(ch)
        f = 'σ' if d == 'ς' else d
        if f and f != ch:
            t[ch] = f
    for cp in range(0x400, 0x500):
        ch = chr(cp)
        if ch.lower() != ch:
            t[ch] = ch.lower()
    return dict(sorted(t.items()))


def main():
    t = table()
    js = ('// GENERATED by tools/offlinemap_fold.py -- edit that file, not this one.\n'
          '// Name folding for search keys; apps/offlinemap/src/fold.lua folds the same way.\n'
          f'const T = {json.dumps(t, ensure_ascii=False, separators=(",", ":"))};\n'
          f'const SEP = new Set({json.dumps(list(SEP), ensure_ascii=False)});\n'
          'export function fold(s) {\n'
          "  let out = '';\n"
          '  for (const ch of String(s)) {\n'
          "    if (SEP.has(ch)) out += ' ';\n"
          "    else if (ch >= 'A' && ch <= 'Z') out += ch.toLowerCase();\n"
          '    else out += T[ch] ?? ch;\n'
          '  }\n'
          "  return out.split(' ').filter(Boolean).join(' ');\n"
          '}\n')
    lua_items = ','.join(f'[{json.dumps(k, ensure_ascii=False)}]={json.dumps(v, ensure_ascii=False)}' for k, v in t.items())
    sep_items = ','.join(f'[{json.dumps(c, ensure_ascii=False)}]=true' for c in SEP)
    lua = ('-- GENERATED by tools/offlinemap_fold.py -- edit that file, not this one.\n'
           '-- Name folding for search keys; site/tools/offlinemap/fold.js folds the same way.\n'
           'local T = {' + lua_items + '}\n'
           'local SEP = {' + sep_items + '}\n'
           'local F = {}\n'
           '-- fold(s): lowercase, accents off (Latin, Greek), separators to one space, trimmed\n'
           'function F.fold(s)\n'
           '  local out = {}\n'
           "  for ch in tostring(s or ''):gmatch('[%z\\1-\\127\\194-\\244][\\128-\\191]*') do\n"
           "    if SEP[ch] then out[#out + 1] = ' '\n"
           "    elseif #ch == 1 and ch >= 'A' and ch <= 'Z' then out[#out + 1] = ch:lower()\n"
           '    else out[#out + 1] = T[ch] or ch end\n'
           '  end\n'
           "  local r = table.concat(out):gsub(' +', ' ')\n"
           "  return (r:gsub('^ ', ''):gsub(' $', ''))\n"
           'end\n'
           'return F\n')
    for path, text in ((os.path.join(ROOT, 'site', 'tools', 'offlinemap', 'fold.js'), js),
                       (os.path.join(ROOT, 'apps', 'offlinemap', 'src', 'fold.lua'), lua)):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w', encoding='utf-8', newline='\n').write(text)
        print(f'{os.path.relpath(path, ROOT)}: {len(text)} B, {len(t)} letters')


if __name__ == '__main__':
    main()
