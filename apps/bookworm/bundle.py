"""Bundle Bookworm: index.lua (tools/gamekit/gamekit.lua + src/*.lua, main.lua last) and
lockscreen.lua (src/taste.lua, src/pet.lua, src/lines*.lua and src/art.lua behind a require, with P, L, A global,
then src/lock/lock.lua;
the sleep screen has no gamekit). Each entry loads on its own.

  python apps/bookworm/bundle.py
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(HERE)), 'tools', 'gamekit'))
import bundle  # noqa: E402


def lockscreen():
    parts = ['-- GENERATED by apps/bookworm/bundle.py from src/pet.lua, src/lines.lua, src/art.lua and src/lock/lock.lua\n'
             '-- -- edit those files, not this one.\n']
    parts.append('''
local __mods, __loaded = {}, {}
local function require(n)
  local v = __loaded[n]
  if v ~= nil then return v end
  v = __mods[n]()
  __loaded[n] = v
  return v
end
''')
    for name in ('taste', 'pet', 'lines', 'lines_ink', 'lines_dragon', 'art'):
        body = open(os.path.join(HERE, 'src', name + '.lua'), encoding='utf-8').read().rstrip('\n')
        parts.append(f"\n__mods['{name}'] = function()\n{body}\nend\n")
    parts.append("\nP, L, A = require('pet'), require('lines'), require('art')\n")
    parts.append('\n' + open(os.path.join(HERE, 'src', 'lock', 'lock.lua'), encoding='utf-8').read())
    text = ''.join(parts)
    out = os.path.join(HERE, 'lockscreen.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'bookworm: lockscreen.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle.bundle(HERE)
    lockscreen()
