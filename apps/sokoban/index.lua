------------------------------------------------------------------ pack text

local function is_board_line(line)
  return line:find('#') ~= nil and line:match('^[ #@+$*.%-_]*$') ~= nil
end

-- Strips a leading comment marker and surrounding quotes; a bare number becomes "Level N".
local function norm_title(t)
  t = (t or ''):gsub('^[;%s]+', ''):gsub('%s+$', '')
  local q = t:sub(1, 1)
  if #t >= 2 and (q == "'" or q == '"') and t:sub(-1) == q then t = t:sub(2, -2):gsub('^%s+', ''):gsub('%s+$', '') end
  if t:match('^%d+$') then t = 'Level ' .. t end
  if t == '' then return nil end
  return t
end

-- A level's title is a "Title:" line right after it (sokobano.de) or else the last non-empty,
-- non-board line before it ("; 12", "Level 12", "'MICROCOSMOS 12'"); prepare_data.py uses the same rule.
local function parse_pack(text)
  local levels, cur, before, pending = {}, {}, nil, nil
  for raw in (text .. '\n'):gmatch('([^\n]*)\n') do
    local line = raw:gsub('\r', '')
    if is_board_line(line) then
      if #cur == 0 then before = pending end
      cur[#cur + 1] = line
    else
      if #cur > 0 then
        local t = line:match('^Title:%s*(.-)%s*$')
        levels[#levels + 1] = { rows = cur, title = norm_title(t or before) }
        cur, before = {}, nil
        pending = (not t and line:match('^%s*(.-)%s*$') ~= '' and line:match('^%s*(.-)%s*$')) or nil
      elseif line:match('%S') then
        pending = line:match('^%s*(.-)%s*$')
      end
    end
  end
  if #cur > 0 then levels[#levels + 1] = { rows = cur, title = norm_title(before) } end
  return levels
end

------------------------------------------------------------------ data section

local function read_text(name)
  local ok, r = pcall(function() return ctx.data:open_text(name) end)
  if ok and r ~= nil and type(r) ~= 'string' then
    local parts = {}
    pcall(function()
      for _ = 1, 50000 do
        local line = r:read_line()
        if line == nil then break end
        parts[#parts + 1] = line
      end
    end)
    pcall(function() r:close() end)
    if #parts > 0 then return table.concat(parts, '\n') .. '\n' end
  end
  local ok2, s = pcall(function() return ctx.data:read_text(name) end)
  if ok2 and type(s) == 'string' then return s end
  return nil
end

local function load_sets()
  SETS = {}
  local text = read_text('banks.tsv')
  if text then
    local counts = {}
    for line in text:gmatch('([^\n]*)\n') do
      local file, count, _, label = line:match('^([^\t]+)\t(%d+)\t(%d+)\t?([^\t]*)')
      if file then
        counts[file] = tonumber(count)
        if not file:find('%.idx%.tsv$') and file ~= 'banks.tsv' then
          SETS[#SETS + 1] = { name = file, file = file, label = (label ~= '' and label) or file, count = 0 }
        end
      end
    end
    for _, s in ipairs(SETS) do
      local ix = s.file:gsub('%.%w+$', '') .. '.idx.tsv'
      if counts[ix] then s.idx_file = ix; s.count = counts[ix] end     -- one index line per level
    end
    data_ok = #SETS > 0
  end
  SETS[#SETS + 1] = { name = 'builtin', label = 'built-in', count = #parse_pack(BUILTIN_PACK) }
end

local function set_by_name(name)
  for i, s in ipairs(SETS) do if s.name == name then return s, i end end
  return SETS[1], 1
end

local function load_index(set)
  local text = read_text(set.idx_file)
  set.idx = {}
  if not text then return false end
  for line in text:gmatch('([^\n]*)\n') do
    local off, title = line:match('^(%d+)\t?(.*)$')
    if off then set.idx[#set.idx + 1] = { off = tonumber(off), title = title:gsub('\r', '') } end
  end
  set.count = #set.idx
  return #set.idx > 0
end

-- Level n of a set -> { rows = {...}, title = ... } or nil.
local function get_level(set, n)
  if set.name == 'builtin' or not set.idx_file then
    if PARSED.name ~= set.name then
      local text = (set.name == 'builtin') and BUILTIN_PACK or read_text(set.file)
      PARSED = { name = set.name, levels = text and parse_pack(text) or {} }
      set.count = #PARSED.levels
    end
    return PARSED.levels[n]
  end
  if not set.idx and not load_index(set) then return nil end
  local e = set.idx[n]
  if not e then return nil end
  local ok, r = pcall(function() return ctx.data:open_text(set.file) end)
  if not ok or r == nil or type(r) == 'string' then return nil end
  local rows = {}
  pcall(function()
    if e.off > 0 and not r:seek(e.off) then error('seek') end
    for _ = 1, 80 do
      local line = r:read_line()
      if line == nil then break end
      line = line:gsub('\r', '')
      if is_board_line(line) then rows[#rows + 1] = line
      elseif #rows > 0 then break end
    end
  end)
  pcall(function() r:close() end)
  if #rows == 0 then return nil end
  return { rows = rows, title = e.title }
end

------------------------------------------------------------------ the level

local DIRS = { l = { 0, -1 }, r = { 0, 1 }, u = { -1, 0 }, d = { 1, 0 } }

local function build_level(def)
  local cols = 0
  for _, row in ipairs(def.rows) do if #row > cols then cols = #row end end
  local grid, pr, pc = {}, nil, nil
  for r, row in ipairs(def.rows) do
    grid[r] = {}
    for c = 1, cols do
      local ch = row:sub(c, c)
      if ch == '' or ch == '-' or ch == '_' then ch = ' ' end
      if ch == '@' then pr, pc, ch = r, c, ' '
      elseif ch == '+' then pr, pc, ch = r, c, '.' end
      grid[r][c] = ch
    end
  end
  walls_total = 0
  for r = 1, #grid do for c = 1, cols do if grid[r][c] == '#' then walls_total = walls_total + 1 end end end
  return { grid = grid, rows = #grid, cols = cols, pr = pr or 1, pc = pc or 1, moves = 0, pushes = 0,
           solved = false, title = def.title }
end

local function cell(lv, r, c)
  if r < 1 or r > lv.rows or c < 1 or c > lv.cols then return '#' end
  return lv.grid[r][c]
end

local function is_solved(lv)
  for r = 1, lv.rows do for c = 1, lv.cols do if lv.grid[r][c] == '$' then return false end end end
  return true
end

local function step(lv, dkey)
  local d = DIRS[dkey]
  local r1, c1 = lv.pr + d[1], lv.pc + d[2]
  local dest = cell(lv, r1, c1)
  if dest == '#' then return nil end
  local pushed = false
  if dest == '$' or dest == '*' then
    local r2, c2 = r1 + d[1], c1 + d[2]
    local behind = cell(lv, r2, c2)
    if behind == '#' or behind == '$' or behind == '*' then return nil end
    lv.grid[r2][c2] = (behind == '.') and '*' or '$'
    lv.grid[r1][c1] = (dest == '*') and '.' or ' '
    lv.pushes = lv.pushes + 1
    pushed = true
  end
  lv.pr, lv.pc = r1, c1
  lv.moves = lv.moves + 1
  lv.solved = is_solved(lv)
  return pushed and dkey:upper() or dkey
end

local function unstep(lv, letter)
  local dkey = letter:lower()
  local d = DIRS[dkey]
  local pr, pc = lv.pr, lv.pc
  if letter ~= dkey then
    local br, bc = pr + d[1], pc + d[2]
    local there = cell(lv, br, bc)
    lv.grid[br][bc] = (there == '*') and '.' or ' '
    lv.grid[pr][pc] = (lv.grid[pr][pc] == '.') and '*' or '$'
    lv.pushes = lv.pushes - 1
  end
  lv.pr, lv.pc = pr - d[1], pc - d[2]
  lv.moves = lv.moves - 1
  lv.solved = is_solved(lv)
end

------------------------------------------------------------------ state

local function best_key() return S.set .. '/' .. S.idx end

-- Loads level idx of set (wrapping), replays hist as far as it fits. Falls back to the built-in pack.
local function start_level(set, idx, hist)
  local n = math.max(set.count, 1)
  idx = ((idx - 1) % n) + 1
  local def = get_level(set, idx)
  if not def and set.count > n then idx = ((idx - 1) % set.count) + 1; def = get_level(set, idx) end
  if not def and set.name ~= 'builtin' then
    msg = 'pack read failed, using built-in'
    set = set_by_name('builtin'); idx = 1; def = get_level(set, 1)
  end
  S.set, S.idx, S.hist = set.name, idx, ''
  S.pos[set.name] = idx
  L = build_level(def or { rows = { '#@#' } })
  for letter in (hist or ''):gmatch('.') do
    local ok = DIRS[letter:lower()] and step(L, letter:lower())
    if not ok then break end
    S.hist = S.hist .. ok
  end
  if not msg or msg == '' then msg = L.title end
  confirm = false
  mode = 'play'
  moves_since_full = 0
  pcall(function() ctx.display:full_refresh() end)
end

local function adopt_state(state)
  S = state
  if type(S.best) ~= 'table' then S.best = {} end
  if type(S.pos) ~= 'table' then S.pos = {} end
  local set = set_by_name(S.set)
  local idx = (math.type(S.idx) == 'integer' and S.idx > 0) and S.idx or (S.pos[set.name] or 1)
  msg = nil
  start_level(set, idx, type(S.hist) == 'string' and S.hist or '')
end

local function after_move()
  if L.solved then
    local k = best_key()
    if type(S.best[k]) ~= 'number' or L.moves < S.best[k] then S.best[k] = L.moves end
    msg = 'Solved!  ' .. L.moves .. ' moves, ' .. L.pushes .. ' pushes'
  end
end

local function do_move(dkey)
  if confirm or mode ~= 'play' or not L or L.solved then return end
  local letter = step(L, dkey)
  if not letter then return end
  S.hist = S.hist .. letter
  msg = nil
  after_move()
  moves_since_full = moves_since_full + 1
  if moves_since_full >= FULL_EVERY then
    moves_since_full = 0
    pcall(function() ctx.display:full_refresh() end)
  end
end

local function undo()
  if confirm or #S.hist == 0 then return end
  unstep(L, S.hist:sub(-1))
  S.hist = S.hist:sub(1, -2)
  msg = nil
end

local function goto_level(delta)
  local set = set_by_name(S.set)
  msg = nil
  start_level(set, S.idx + delta, '')
end

local function choose_set(i)
  local set = SETS[i]
  if not set then return end
  msg = nil
  if set.name == S.set then mode = 'play'; return end
  start_level(set, S.pos[set.name] or 1, '')
end

------------------------------------------------------------------ drawing

local function text_w(s)
  local ok, w = pcall(function() return g:measure_text(s) end)
  if ok and type(w) == 'number' and w > 0 then return w end
  return 13 * #s
end
local function ctext(cx, cy, s) g:text(cx - text_w(s) // 2, cy - 12, s) end
local function rtext(right, y, s) g:text(right - text_w(s), y, s) end
local function inside(b, x, y) return x >= b.x and x < b.x + b.w and y >= b.y and y < b.y + b.h end
local function short(s, n) s = tostring(s); if #s > n then return s:sub(1, n - 1) .. '~' end return s end

local function geometry()
  local cs = math.min(MAX_CELL, 450 // L.cols, (BOARD_Y1 - BOARD_Y0) // L.rows)
  if cs < MIN_CELL then cs = MIN_CELL end
  local x0 = (480 - cs * L.cols) // 2
  local y0 = BOARD_Y0 + ((BOARD_Y1 - BOARD_Y0) - cs * L.rows) // 2
  return cs, x0, y0
end

local function draw_board()
  local cs, x0, y0 = geometry()
  for r = 1, L.rows do
    for c = 1, L.cols do
      local ch = L.grid[r][c]
      local x, y = x0 + (c - 1) * cs, y0 + (r - 1) * cs
      local cx, cy = x + cs // 2, y + cs // 2
      if ch == '#' then
        g:rect(x, y, cs, cs)                        -- plain outline: little black, little ghosting
      elseif ch == '.' then
        g:circle(cx, cy, math.max(2, cs // 6))
      elseif ch == '$' or ch == '*' then
        g:rect(x + 3, y + 3, cs - 6, cs - 6)
        g:rect(x + 6, y + 6, cs - 12, cs - 12)
        if ch == '*' then
          g:line(x + 8, y + 8, x + cs - 9, y + cs - 9); g:line(x + cs - 9, y + 8, x + 8, y + cs - 9)
        end
      end
      if r == L.pr and c == L.pc then
        g:circle(cx, cy, math.max(3, cs // 3)); g:circle(cx, cy, 1)
      end
    end
  end
end

local function draw_confirm()
  g:rect(DLG.x, DLG.y, DLG.w, DLG.h); g:rect(DLG.x + 2, DLG.y + 2, DLG.w - 4, DLG.h - 4)
  ctext(240, DLG.y + 50, 'Restart this level?')
  ctext(240, DLG.y + 86, 'Your moves will be lost.')
  g:rect(YES.x, YES.y, YES.w, YES.h); ctext(YES.x + YES.w // 2, YES.y + YES.h // 2, 'Yes')
  g:rect(NO.x, NO.y, NO.w, NO.h);     ctext(NO.x + NO.w // 2, NO.y + NO.h // 2, 'No')
end

local function pages() return math.max(1, math.ceil(#SETS / LIST_ROWS)) end

local function draw_sets()
  g:text(15, 14, 'Level sets')
  rtext(465, 14, 'page ' .. page .. '/' .. pages())
  g:line(15, 74, 465, 74)
  local first = (page - 1) * LIST_ROWS
  for i = 1, LIST_ROWS do
    local s = SETS[first + i]
    if not s then break end
    local y = LIST_Y0 + (i - 1) * LIST_ROW
    local mark = (s.name == S.set) and '> ' or '  '
    g:text(25, y + 8, mark .. short(s.label, 26))
    if s.count and s.count > 0 then rtext(455, y + 8, tostring(s.count)) end
    g:line(15, y + LIST_ROW - 1, 465, y + LIST_ROW - 1)
  end
  for k, b in ipairs(PBTN) do
    local x = BTN_X + (k - 1) * (PBTN_W + PBTN_GAP)
    g:rect(x, BTN_Y, PBTN_W, BTN_H)
    ctext(x + PBTN_W // 2, BTN_Y + BTN_H // 2, b[2])
  end
  ctext(240, 712, 'tap a set to play it')
end

local function btn_label(id)
  if id == 'undo' then return 'Undo' elseif id == 'reset' then return 'Reset'
  elseif id == 'prev' then return 'Prev' elseif id == 'next' then return 'Next' else return 'Set' end
end

local function draw_impl()
  g:clear(0)
  if mode == 'sets' then draw_sets(); return end
  local set = set_by_name(S.set)
  g:text(15, 14, 'Sokoban')
  rtext(465, 14, short(set.label, 14) .. '  ' .. S.idx .. '/' .. set.count)
  local best = S.best[best_key()]
  g:text(15, 44, 'moves ' .. L.moves .. '   pushes ' .. L.pushes .. (best and ('   best ' .. best) or ''))
  g:line(15, 74, 465, 74)
  if confirm then draw_confirm() else draw_board() end
  for k, id in ipairs(BTNS) do
    local x = BTN_X + (k - 1) * (BTN_W + BTN_GAP)
    g:rect(x, BTN_Y, BTN_W, BTN_H)
    ctext(x + BTN_W // 2, BTN_Y + BTN_H // 2, btn_label(id))
  end
  if msg then ctext(240, 712, short(msg, 36))
  elseif not data_ok then ctext(240, 712, 'built-in pack (no data section)') end
  g:line(15, 752, 465, 752)
  ctext(240, 776, 'swipe, or tap beside the player')
end

------------------------------------------------------------------ input and lifecycle

local function tap_sets(x, y)
  if y >= BTN_Y and y < BTN_Y + BTN_H then
    local k = (x - BTN_X) // (PBTN_W + PBTN_GAP)
    if k < 0 or k > 2 or x - BTN_X - k * (PBTN_W + PBTN_GAP) >= PBTN_W then return end
    local id = PBTN[k + 1][1]
    if id == 'pgup' then page = math.max(1, page - 1)
    elseif id == 'pgdn' then page = math.min(pages(), page + 1)
    else mode = 'play' end
    return
  end
  if y >= LIST_Y0 and y < LIST_Y0 + LIST_ROWS * LIST_ROW then
    local i = (page - 1) * LIST_ROWS + (y - LIST_Y0) // LIST_ROW + 1
    choose_set(i)
  end
end

local function tap(x, y)
  if mode == 'sets' then tap_sets(x, y); return end
  if confirm then
    if inside(YES, x, y) then goto_level(0); pcall(function() ctx.display:full_refresh() end)
    elseif inside(NO, x, y) then confirm = false end
    return
  end
  if y >= BTN_Y and y < BTN_Y + BTN_H then
    local k = (x - BTN_X) // (BTN_W + BTN_GAP)
    if k < 0 or k > 4 or x - BTN_X - k * (BTN_W + BTN_GAP) >= BTN_W then return end
    local id = BTNS[k + 1]
    if id == 'undo' then undo()
    elseif id == 'reset' then if #S.hist > 0 then confirm = true end
    elseif id == 'prev' then goto_level(-1)
    elseif id == 'next' then goto_level(1)
    elseif id == 'set' then
      local _, i = set_by_name(S.set)
      page = (i - 1) // LIST_ROWS + 1
      mode = 'sets'
    end
    return
  end
  if y >= BOARD_Y0 and y < BOARD_Y1 and L then
    local cs, x0, y0 = geometry()
    local px, py = x0 + (L.pc - 1) * cs + cs // 2, y0 + (L.pr - 1) * cs + cs // 2
    local dx, dy = x - px, y - py
    if math.abs(dx) < cs // 2 and math.abs(dy) < cs // 2 then return end
    if math.abs(dx) >= math.abs(dy) then do_move(dx < 0 and 'l' or 'r') else do_move(dy < 0 and 'u' or 'd') end
  end
end

local function input_impl(ev)
  if type(ev) ~= 'table' then return false end
  if ev.type == 'key' then
    if ev.state ~= nil and ev.state ~= 'down' then return true end
    if mode == 'sets' then
      if ev.key == 'up' then page = math.max(1, page - 1) elseif ev.key == 'down' then page = math.min(pages(), page + 1) end
    elseif L and L.solved and ev.key == 'down' then goto_level(1)
    elseif ev.key == 'up' then do_move('u')
    elseif ev.key == 'down' then do_move('d') end
    pcall(ctx.invalidate)
    return true
  end
  if ev.type == 'touch' then
    local gs = ev.gesture
    if gs ~= 'tap' and ev.x == 0 and ev.y == 0 then return true end
    if gs == 'tap' then tap(ev.x or 0, ev.y or 0)
    elseif mode == 'play' then
      if gs == 'swipe_left' then do_move('l')
      elseif gs == 'swipe_right' then do_move('r')
      elseif gs == 'swipe_up' then do_move('u')
      elseif gs == 'swipe_down' then do_move('d') end
    end
    pcall(ctx.invalidate)
    return true
  end
  return false
end

local function load_impl(c)
  c = c or ctx
  if type(c.state) ~= 'table' then c.state = {} end
  load_sets()
  adopt_state(c.state)
end

------------------------------------------------------------------ error reporting
-- The host closes an app on any Lua error and only says "App error, closed". These wrappers catch
-- the error and paint it, so a failure on the device can actually be read.
local ERR = nil

local function show_error(where, err)
  ERR = where .. ': ' .. tostring(err)
end

local function draw_error()
  g:clear(0)
  g:text(15, 20, 'Sokoban: Lua error')
  g:line(15, 52, 465, 52)
  local y, s = 70, ERR
  while #s > 0 and y < 740 do
    g:text(15, y, s:sub(1, 36)); s = s:sub(37); y = y + 26
  end
  g:text(15, 770, 'Home pad leaves the app')
end

function on_load(c)
  local ok, err = pcall(load_impl, c)
  if not ok then show_error('on_load', err) end
end

function on_draw()
  if ERR then draw_error(); return end
  local ok, err = pcall(draw_impl)
  if not ok then show_error('on_draw', err); pcall(draw_error) end
end

function on_input(_, ev)
  if ERR then return true end
  local ok, res = pcall(input_impl, ev)
  if not ok then show_error('on_input', res); pcall(ctx.invalidate); return true end
  return res
end

function on_leave() end     -- the host saves ctx.state itself

