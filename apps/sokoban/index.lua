-- Sokoban for XTOS Licorice mini apps (Lua API 0.8, 480 x 800 portrait, 1 bpp).
--
-- Rules as in CPR-vCodex's SokobanGame: the player moves one cell at a time; a box in the way is
-- pushed when the cell behind it is free; a level is solved when no box is off a goal. Undo takes
-- back one move (and its push); Reset asks first.
--
-- Level packs live in the package's DATA section as plain XSB text (sokoban/prepare_data.py puts
-- them in sokoban/data/ with a per-pack index "<name>.idx.tsv" = "<byte offset>\t<title>" per
-- level; xtpack.py packs them and lists every file in banks.tsv). A level is read by seeking to
-- its offset and taking the run of board lines there (lines of "# @ + $ * . - _" and spaces with
-- a '#'), so packs of any size cost one small read per level. A pack without an index is read
-- whole and parsed (fine for small ones). Without a data section the built-in pack below is used.
--
-- Controls: swipe; tap the board on the side of the player you want to go; side buttons up / down
-- (after a solve the lower one goes to the next level). Buttons: Undo, Reset, Prev, Next, Set
-- (opens the pack list). ctx.state keeps the move history (LURD letters, upper case = push), the
-- current pack, the last level of every pack and the best move count per level.

