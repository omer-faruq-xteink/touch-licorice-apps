"""Bundle xkcd into index.lua (tools/gamekit/gamekit.lua + src/xk.lua + src/main.lua) and
lockscreen.lua (gamekit as `kit` + src/xk.lua as `X` + src/lock/lock.lua: a lock entry loads alone,
without the app).

  python apps/xkcd/bundle.py
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_DIR = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'tools', 'gamekit')
sys.path.insert(0, KIT_DIR)
import bundle  # noqa: E402


def bundle_lock():
    src = os.path.join(HERE, 'src', 'lock', 'lock.lua')
    if not os.path.exists(src):
        return
    kit = open(os.path.join(KIT_DIR, 'gamekit.lua'), encoding='utf-8').read().rstrip('\n')
    xk = open(os.path.join(HERE, 'src', 'xk.lua'), encoding='utf-8').read().rstrip('\n')
    text = ('-- GENERATED by apps/xkcd/bundle.py from tools/gamekit/gamekit.lua, src/xk.lua and src/lock/lock.lua'
            ' -- edit those files, not this one.\n'
            'local kit = (function()\n' + kit + '\nend)()\n\n'
            'local X = (function()\n' + xk + '\nend)()\n\n' + open(src, encoding='utf-8').read())
    out = os.path.join(HERE, 'lockscreen.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'xkcd: lockscreen.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle.bundle(HERE)
    bundle_lock()
