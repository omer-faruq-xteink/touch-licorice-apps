-- ink runs of each picture: { x, y, length } in picture pixels
local runs = {}
for name, rows in pairs(S) do
  local r = {}
  for y, row in ipairs(rows) do
    local x = 1
    while x <= #row do
      if row:sub(x, x) == '#' then
        local e = x
        while e < #row and row:sub(e + 1, e + 1) == '#' do e = e + 1 end
        r[#r + 1] = { x - 1, y - 1, e - x + 1 }
        x = e + 1
      else x = x + 1 end
    end
  end
  runs[name] = r
end

return { art = S, runs = runs }
