"""Bundle Weather: index.lua (tools/gamekit/gamekit.lua + src/wx.lua + src/main.lua) and
lockscreen.lua (src/wx.lua as `X` + src/lock/lock.lua: a lock entry loads alone, without the app).

  python apps/weather/bundle.py
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(HERE)), 'tools', 'gamekit'))
import bundle  # noqa: E402


def bundle_lock():
    wx = open(os.path.join(HERE, 'src', 'wx.lua'), encoding='utf-8').read().rstrip('\n')
    lock = open(os.path.join(HERE, 'src', 'lock', 'lock.lua'), encoding='utf-8').read()
    text = ('-- GENERATED by apps/weather/bundle.py from src/wx.lua and src/lock/lock.lua -- edit those files, not this one.\n'
            'local X = (function()\n' + wx + '\nend)()\n\n' + lock)
    out = os.path.join(HERE, 'lockscreen.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'weather: lockscreen.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle.bundle(HERE)
    bundle_lock()
