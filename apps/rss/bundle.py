"""Bundle RSS into index.lua: src/main.lua, with the other src/*.lua (feeds.lua) as modules main
reaches with require('<name>'), since the device has no require for package files.

  python apps/rss/bundle.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def bundle():
    src = os.path.join(HERE, 'src')
    parts = ["-- GENERATED by apps/rss/bundle.py from apps/rss/src/ -- edit those files, not this one.\n",
             """
local __mods, __loaded = {}, {}
local function require(n)
  local v = __loaded[n]
  if v ~= nil then return v end
  local f = __mods[n]
  if not f then error('module not found: ' .. tostring(n)) end
  v = f()
  if v == nil then v = true end
  __loaded[n] = v
  return v
end
"""]
    for f in sorted(os.listdir(src)):
        if f.endswith('.lua') and f != 'main.lua':
            body = open(os.path.join(src, f), encoding='utf-8').read().rstrip('\n')
            parts.append(f"\n__mods['{f[:-4]}'] = function()\n{body}\nend\n")
    parts.append('\n' + open(os.path.join(src, 'main.lua'), encoding='utf-8').read())
    text = ''.join(parts)
    out = os.path.join(HERE, 'index.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'rss: index.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle()
