-- Suguru (Tectonic) for XTOS Licorice mini apps (Lua API 0.8, 480 x 800 portrait, 1 bpp).
--
-- Rules: the grid is split into regions of 1..5 cells (thick borders); a region of n cells holds
-- 1..n once each; touching cells, diagonals included, never hold the same number. Givens are fixed.
-- "Solved" means every cell is filled and no rule is broken (the banks have unique solutions).
-- Mistake marking (Chk) crosses the cells that break a rule right now.
--
-- Puzzle banks: the package's DATA section (made by make_bank.py; xtpack.py packs suguru/data/*.txt
-- and writes banks.tsv "file<TAB>count<TAB>stride<TAB>label"). Each line is one puzzle: n*n region
-- letters, then n*n digits (0 = empty), so puzzle N is read with reader:seek((N - 1) * stride).
-- When the data section is missing the small bank embedded below is used.
--
-- Drawing is deliberately heavy for e-ink: 3 px region borders and digits drawn twice, one pixel
-- apart, so the grid stays readable on panels that show thin lines faintly.
--
-- Controls: tap a cell, then a number; Erase clears; Chk toggles mistake marking; Next / Bank move
-- on; the side buttons go to the previous / next puzzle. Progress lives in ctx.state.

local GRID_W = 450
local GX, GY = 15, 90                        -- grid origin; a cell is GRID_W // n wide
local PAD_Y, PAD_H, PAD_W, PAD_GAP, PAD_X = 572, 60, 82, 10, 15   -- 5 * 82 + 4 * 10 = 450
local ACT_Y, ACT_H, ACT_W, ACT_GAP, ACT_X = 644, 56, 105, 10, 15  -- 4 * 105 + 3 * 10 = 450
local ACTS = { 'erase', 'check', 'next', 'bank' }

-- BUILTIN-BEGIN (generated by make_bank.py)
local BUILTIN_PUZZLES = {
  'AAAAABBCCCBBCCDBEDDDFEEEE0010500000202040000000000',
  'AAAAABCCCCBBDEEBBDDEFFDDE2300510000000004000000301',
  'AAAABCADDDCCEDDCEEEFGGEFF0403000004100303000000000',
  'AABBBBAACDBEFACDEEFFGDDEHHGGIEHHHGII000400030000040000000010000000040000',
  'ABBBCDAEBCCDAEEFCCAAEFFFGGEHFIGGGIII000000000040300000002030000004105000',
  'AAABBCDBBBCCDEEFCCDFFFFGDDHIIIHHHHII200000000042000000300000400340300000',
}
-- BUILTIN-END

local S                 -- ctx.state: bank, idx, n, regions, givens, cells, sel, check, solved
local BANKS = {}        -- { {name=, label=, count=, stride=, file=} ... }, built-in last
local msg = nil
local data_ok = false
local entries_since_full = 0
local FULL_EVERY = 8    -- e-ink: full refresh this often to clear ghosting

------------------------------------------------------------------ puzzle text

-- one bank line -> n, regions, givens, or nil
local function parse_line(line)
  if type(line) ~= 'string' then return nil end
  line = line:gsub('[\r\n]', '')
  local half = #line // 2
  if half * 2 ~= #line then return nil end
  local n = math.floor(math.sqrt(half) + 0.5)
  if n < 4 or n > 9 or n * n ~= half then return nil end
  local regions, givens = line:sub(1, half), line:sub(half + 1)
  if regions:find('[^%w]') or givens:find('[^0-5]') then return nil end
  return n, regions, givens
end

------------------------------------------------------------------ banks (data section + built-in)

local function open_text(name)
  local ok, r, err = pcall(function() return ctx.data:open_text(name) end)
  if ok and r ~= nil and type(r) ~= 'string' then return r end
  return nil, (ok and err) or r
end

local function load_banks()
  BANKS = {}
  local r = open_text('banks.tsv')
  if r then
    for _ = 1, 128 do
      local ok, line = pcall(function() return r:read_line() end)
      if not ok or line == nil then break end
      local file, count, stride, label = line:match('^([^\t]+)\t(%d+)\t(%d+)\t?([^\t]*)')
      if file and tonumber(count) and tonumber(count) > 0 then
        BANKS[#BANKS + 1] = { name = file, label = (label ~= '' and label) or file,
                              count = tonumber(count), stride = tonumber(stride), file = file }
      end
    end
    pcall(function() r:close() end)
    data_ok = #BANKS > 0
  end
  BANKS[#BANKS + 1] = { name = 'builtin', label = 'built-in', count = #BUILTIN_PUZZLES, stride = 0 }
end

local function bank_by_name(name)
  for i, b in ipairs(BANKS) do if b.name == name then return b, i end end
  return BANKS[1], 1
end

local function read_puzzle(bank, idx)
  if bank.name == 'builtin' then return parse_line(BUILTIN_PUZZLES[idx]) end
  local r = open_text(bank.file)
  if not r then return nil end
  local line
  local ok = pcall(function()
    if bank.stride and bank.stride > 0 and idx > 1 then
      if not r:seek((idx - 1) * bank.stride) then error('seek') end
      line = r:read_line()
    else
      for _ = 1, idx do line = r:read_line() end
    end
  end)
  pcall(function() r:close() end)
  if not ok then return nil end
  return parse_line(line)
end

------------------------------------------------------------------ rules

-- bad[i] = true when the number in cell i breaks a rule: bigger than its region, repeated in its
-- region, or equal to a touching cell (diagonals too)
local function conflicts(n, regions, cells)
  local bad = {}
  local size, seen = {}, {}
  for i = 1, n * n do local r = regions:sub(i, i); size[r] = (size[r] or 0) + 1 end
  for i = 1, n * n do
    local v = cells:sub(i, i)
    if v ~= '0' then
      local r = regions:sub(i, i)
      if tonumber(v) > size[r] then bad[i] = true end
      local key = r .. v
      if seen[key] then bad[i] = true; bad[seen[key]] = true else seen[key] = i end
      local row, col = (i - 1) // n, (i - 1) % n
      for dr = -1, 1 do
        for dc = -1, 1 do
          local rr, cc = row + dr, col + dc
          if (dr ~= 0 or dc ~= 0) and rr >= 0 and rr < n and cc >= 0 and cc < n then
            local j = rr * n + cc + 1
            if cells:sub(j, j) == v then bad[i] = true; bad[j] = true end
          end
        end
      end
    end
  end
  return bad
end

local function is_solved(n, regions, cells)
  if cells:find('0') then return false end
  return next(conflicts(n, regions, cells)) == nil
end

------------------------------------------------------------------ state

local function set_puzzle(bank, idx, n, regions, givens)
  S.bank, S.idx, S.n, S.regions, S.givens, S.cells = bank.name, idx, n, regions, givens, givens
  S.sel, S.solved = nil, false
end

local function load_puzzle(bank, idx)
  idx = ((idx - 1) % math.max(bank.count, 1)) + 1
  local n, regions, givens = read_puzzle(bank, idx)
  if not n and bank.name ~= 'builtin' then
    msg = 'bank read failed, using built-in'
    bank = bank_by_name('builtin'); idx = 1; n, regions, givens = read_puzzle(bank, idx)
  end
  if not n then n, regions, givens = 5, string.rep('A', 25), string.rep('0', 25); msg = 'no puzzles found' end
  set_puzzle(bank, idx, n, regions, givens)
end

local function adopt_state(state)
  S = state
  if type(S.check) ~= 'boolean' then S.check = true end
  local bank = bank_by_name(S.bank)
  local idx = (math.type(S.idx) == 'integer' and S.idx > 0) and S.idx or 1
  local n = math.type(S.n) == 'integer' and S.n or 0
  local cells_ok = n >= 4 and n <= 9
  for _, k in ipairs({ 'regions', 'givens', 'cells' }) do
    if type(S[k]) ~= 'string' or #S[k] ~= n * n then cells_ok = false end
  end
  if cells_ok and not S.givens:find('[^0-5]') and not S.cells:find('[^0-5]') then
    S.bank, S.idx = bank.name, idx
    if math.type(S.sel) ~= 'integer' or S.sel < 1 or S.sel > n * n then S.sel = nil end
    S.solved = is_solved(n, S.regions, S.cells)
  else
    load_puzzle(bank, idx)
  end
end

local function set_cell(i, d)
  if S.solved then return end
  if S.givens:sub(i, i) ~= '0' then msg = 'that cell is a given'; return end
  S.cells = S.cells:sub(1, i - 1) .. d .. S.cells:sub(i + 1)
  msg = nil
  entries_since_full = entries_since_full + 1
  if entries_since_full >= FULL_EVERY then
    entries_since_full = 0
    pcall(function() ctx.display:full_refresh() end)
  end
  if is_solved(S.n, S.regions, S.cells) then S.solved = true; msg = 'Solved!  Next for another' end
end

local function step_puzzle(delta)
  load_puzzle(bank_by_name(S.bank), S.idx + delta)
  msg = nil
end

local function next_bank()
  local _, i = bank_by_name(S.bank)
  load_puzzle(BANKS[(i % #BANKS) + 1], 1)
  msg = nil
end

------------------------------------------------------------------ drawing

local function text_w(s)
  local ok, w = pcall(function() return g:measure_text(s) end)
  if ok and type(w) == 'number' and w > 0 then return w end
  return 13 * #s
end
local function ctext(cx, cy, s) g:text(cx - text_w(s) // 2, cy - 12, s) end
-- bold: the same text twice, one pixel apart
local function btext(cx, cy, s) ctext(cx, cy, s); ctext(cx + 1, cy, s) end
local function rtext(right, y, s) g:text(right - text_w(s), y, s) end

local function cell_px() return GRID_W // S.n end

-- a 3 px line (offsets -1, 0, +1 across it)
local function thick_v(x, y0, y1) for o = -1, 1 do g:line(x + o, y0, x + o, y1) end end
local function thick_h(y, x0, x1) for o = -1, 1 do g:line(x0, y + o, x1, y + o) end end

local function draw_grid()
  local n, C = S.n, cell_px()
  local x1, y1 = GX + n * C, GY + n * C
  for k = 1, n - 1 do                                    -- thin cell lines
    g:line(GX + k * C, GY, GX + k * C, y1)
    g:line(GX, GY + k * C, x1, GY + k * C)
  end
  local function reg(r, c) return S.regions:sub(r * n + c + 1, r * n + c + 1) end
  for r = 0, n - 1 do                                    -- thick region borders
    for c = 0, n - 1 do
      local x, y = GX + c * C, GY + r * C
      if c < n - 1 and reg(r, c) ~= reg(r, c + 1) then thick_v(x + C, y - 1, y + C + 1) end
      if r < n - 1 and reg(r, c) ~= reg(r + 1, c) then thick_h(y + C, x - 1, x + C + 1) end
    end
  end
  thick_v(GX, GY - 1, y1 + 1); thick_v(x1, GY - 1, y1 + 1)
  thick_h(GY, GX - 1, x1 + 1); thick_h(y1, GX - 1, x1 + 1)
  local bad = S.check and conflicts(n, S.regions, S.cells) or {}
  for r = 0, n - 1 do
    for c = 0, n - 1 do
      local i = r * n + c + 1
      local x, y = GX + c * C, GY + r * C
      if i == S.sel then g:rect(x + 5, y + 5, C - 10, C - 10); g:rect(x + 7, y + 7, C - 14, C - 14) end
      local d = S.cells:sub(i, i)
      if d ~= '0' then
        btext(x + C // 2, y + C // 2, d)
        if S.givens:sub(i, i) == '0' then                -- entered, not given: underlined
          g:line(x + C // 2 - 9, y + C // 2 + 16, x + C // 2 + 9, y + C // 2 + 16)
          g:line(x + C // 2 - 9, y + C // 2 + 17, x + C // 2 + 9, y + C // 2 + 17)
        end
        if bad[i] then
          for o = 0, 1 do
            g:line(x + C - 18 + o, y + 8, x + C - 8 + o, y + 18)
            g:line(x + C - 8 + o, y + 8, x + C - 18 + o, y + 18)
          end
        end
      end
    end
  end
end

local function act_label(id)
  if id == 'erase' then return 'Erase' end
  if id == 'check' then return S.check and 'Chk on' or 'Chk off' end
  if id == 'next' then return 'Next' end
  return 'Bank'
end

local function box(x, y, w, h) g:rect(x, y, w, h); g:rect(x + 1, y + 1, w - 2, h - 2) end

function on_draw()
  g:clear(0)
  local bank = bank_by_name(S.bank)
  btext(GX + text_w('Suguru') // 2, 42, 'Suguru')
  rtext(480 - GX, 30, bank.label .. '  ' .. S.idx .. '/' .. bank.count)
  g:line(GX, 70, 480 - GX, 70); g:line(GX, 71, 480 - GX, 71)
  draw_grid()
  for d = 1, 5 do
    local x = PAD_X + (d - 1) * (PAD_W + PAD_GAP)
    box(x, PAD_Y, PAD_W, PAD_H)
    btext(x + PAD_W // 2, PAD_Y + PAD_H // 2, tostring(d))
  end
  for k, id in ipairs(ACTS) do
    local x = ACT_X + (k - 1) * (ACT_W + ACT_GAP)
    box(x, ACT_Y, ACT_W, ACT_H)
    ctext(x + ACT_W // 2, ACT_Y + ACT_H // 2, act_label(id))
  end
  if msg then ctext(240, 730, msg)
  elseif not data_ok then ctext(240, 730, 'built-in bank (no data section)') end
  g:line(GX, 752, 480 - GX, 752)
  ctext(240, 776, 'tap a cell, then a number')
end

------------------------------------------------------------------ input and lifecycle

local function tap(x, y)
  local n, C = S.n, cell_px()
  if x >= GX and x < GX + n * C and y >= GY and y < GY + n * C then
    S.sel = ((y - GY) // C) * n + (x - GX) // C + 1
    msg = nil
    return
  end
  if y >= PAD_Y and y < PAD_Y + PAD_H then
    local k = (x - PAD_X) // (PAD_W + PAD_GAP)
    if k >= 0 and k < 5 and x - PAD_X - k * (PAD_W + PAD_GAP) < PAD_W then
      if S.sel then set_cell(S.sel, tostring(k + 1)) else msg = 'tap a cell first' end
    end
    return
  end
  if y >= ACT_Y and y < ACT_Y + ACT_H then
    local k = (x - ACT_X) // (ACT_W + ACT_GAP)
    if k < 0 or k > 3 or x - ACT_X - k * (ACT_W + ACT_GAP) >= ACT_W then return end
    local id = ACTS[k + 1]
    if id == 'erase' then if S.sel then set_cell(S.sel, '0') end
    elseif id == 'check' then S.check = not S.check
    elseif id == 'next' then step_puzzle(1)
    elseif id == 'bank' then next_bank() end
  end
end

function on_input(_, ev)
  if type(ev) ~= 'table' then return false end
  if ev.type == 'key' then
    if ev.state ~= nil and ev.state ~= 'down' then return true end
    if ev.key == 'up' then step_puzzle(-1) elseif ev.key == 'down' then step_puzzle(1) end
    pcall(ctx.invalidate)
    return true
  end
  if ev.type == 'touch' then
    if ev.gesture == 'tap' then tap(ev.x or 0, ev.y or 0); pcall(ctx.invalidate) end
    return true
  end
  return false
end

function on_load(c)
  c = c or ctx
  if type(c.state) ~= 'table' then c.state = {} end
  load_banks()
  adopt_state(c.state)
end

function on_leave() end     -- the host saves ctx.state itself

