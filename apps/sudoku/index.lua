local S                 -- ctx.state: bank, idx, givens, cells, sel, check, solved
local BANKS = {}        -- { {name=, label=, count=, stride=, file=} ... }, built-in last
local msg = nil
local data_ok = false   -- the data section answered

------------------------------------------------------------------ puzzle text

local function normalize81(s)
  s = s:gsub('[.%-]', '0')
  if #s ~= 81 or s:find('[^0-9]') then return nil end
  return s
end

-- One line of any supported bank format -> 81-char puzzle string, or nil.
local function parse_line(line)
  if type(line) ~= 'string' then return nil end
  line = line:gsub('\r', '')
  local a = line:match('^([0-9.%-]+),')                              -- Kaggle CSV
  if a and #a == 81 then return normalize81(a) end
  local b = line:match('^%S+%s+([0-9.%-]+)%s') or line:match('^%S+%s+([0-9.%-]+)$')   -- sudoku-exchange
  if b and #b == 81 then return normalize81(b) end
  local c = line:match('^([0-9.%-]+)$')                              -- line81
  if c and #c == 81 then return normalize81(c) end
  return nil
end

------------------------------------------------------------------ banks (data section + built-in)

-- API 2.9 calls the data section ctx.package (API 0.8: ctx.data)
local function open_text(name)
  local D = ctx.package or ctx.data
  if not D then return nil, 'no data section' end
  local ok, r, err = pcall(function() return D:open_text(name) end)
  if ok and r ~= nil and type(r) ~= 'string' then return r end
  return nil, (ok and err) or r
end

local function load_banks()
  BANKS = {}
  local r = open_text('banks.tsv')
  if r then
    for _ = 1, 128 do
      local ok, line = pcall(function() return r:read_line() end)
      if not ok or line == nil then break end
      local file, count, stride, label = line:match('^([^\t]+)\t(%d+)\t(%d+)\t?([^\t]*)')
      if file and tonumber(count) and tonumber(count) > 0 then
        BANKS[#BANKS + 1] = { name = file, label = (label ~= '' and label) or file,
                              count = tonumber(count), stride = tonumber(stride), file = file }
      end
    end
    pcall(function() r:close() end)
    data_ok = #BANKS > 0
  end
  BANKS[#BANKS + 1] = { name = 'builtin', label = 'built-in', count = #BUILTIN_PUZZLES, stride = 0 }
end

local function bank_by_name(name)
  for i, b in ipairs(BANKS) do if b.name == name then return b, i end end
  return BANKS[1], 1
end

-- Puzzle idx (1-based) of a bank -> 81-char string, or nil.
local function read_puzzle(bank, idx)
  if bank.name == 'builtin' then return normalize81(BUILTIN_PUZZLES[idx] or '') end
  local r = open_text(bank.file)
  if not r then return nil end
  local line
  local ok = pcall(function()
    if bank.stride and bank.stride > 0 and idx > 1 and r.seek and r:seek((idx - 1) * bank.stride) then
      line = r:read_line()
    else
      -- no seek on this reader: read up to the line
      pcall(function() r:close() end)
      r = open_text(bank.file)
      for _ = 1, idx do line = r:read_line() end
    end
  end)
  pcall(function() r:close() end)
  if not ok then return nil end
  return parse_line(line)
end

------------------------------------------------------------------ rules

local function cell_index(r, c) return r * 9 + c + 1 end     -- r, c in 0..8

-- conflicts[i] = true when the digit in cell i repeats in its row, column or box.
local function conflicts(cells)
  local bad = {}
  local function unit(ids)
    local seen = {}
    for _, i in ipairs(ids) do
      local d = cells:sub(i, i)
      if d ~= '0' then
        if seen[d] then bad[i] = true; bad[seen[d]] = true else seen[d] = i end
      end
    end
  end
  for r = 0, 8 do
    local row, col = {}, {}
    for c = 0, 8 do row[#row + 1] = cell_index(r, c); col[#col + 1] = cell_index(c, r) end
    unit(row); unit(col)
  end
  for br = 0, 2 do
    for bc = 0, 2 do
      local box = {}
      for r = 0, 2 do for c = 0, 2 do box[#box + 1] = cell_index(br * 3 + r, bc * 3 + c) end end
      unit(box)
    end
  end
  return bad
end

local function is_solved(cells)
  if cells:find('0') then return false end
  return next(conflicts(cells)) == nil
end

------------------------------------------------------------------ state

local function set_puzzle(bank, idx, givens)
  S.bank, S.idx, S.givens, S.cells = bank.name, idx, givens, givens
  S.sel, S.solved = nil, false
end

local function load_puzzle(bank, idx)
  idx = ((idx - 1) % math.max(bank.count, 1)) + 1
  local p = read_puzzle(bank, idx)
  if not p and bank.name ~= 'builtin' then
    msg = 'bank read failed, using built-in'
    bank = bank_by_name('builtin'); idx = 1; p = read_puzzle(bank, idx)
  end
  if not p then p = string.rep('0', 81); msg = 'no puzzles found' end
  set_puzzle(bank, idx, p)
end

local function adopt_state(state)
  S = state
  if type(S.check) ~= 'boolean' then S.check = true end
  local bank, _ = bank_by_name(S.bank)
  local idx = (math.type(S.idx) == 'integer' and S.idx > 0) and S.idx or 1
  local resume = type(S.givens) == 'string' and #S.givens == 81 and type(S.cells) == 'string' and #S.cells == 81
    and not S.givens:find('[^0-9]') and not S.cells:find('[^0-9]')
  if resume then
    S.bank, S.idx = bank.name, idx
    if math.type(S.sel) ~= 'integer' or S.sel < 1 or S.sel > 81 then S.sel = nil end
    S.solved = is_solved(S.cells)
  else
    load_puzzle(bank, idx)
  end
end

local function set_cell(i, d)
  if S.solved then return end
  if S.givens:sub(i, i) ~= '0' then msg = 'that cell is a given'; return end
  S.cells = S.cells:sub(1, i - 1) .. d .. S.cells:sub(i + 1)
  msg = nil
  if is_solved(S.cells) then S.solved = true; msg = 'Solved!  Next for another' end
end

local function step_puzzle(delta)
  local bank = bank_by_name(S.bank)
  load_puzzle(bank, S.idx + delta)
  msg = nil
end

local function next_bank()
  local _, i = bank_by_name(S.bank)
  local bank = BANKS[(i % #BANKS) + 1]
  load_puzzle(bank, 1)
  msg = nil
end

------------------------------------------------------------------ storage

-- ctx.state is the host's, and was all API 0.8 had; state.txt in the app's storage is read first
local function save_state()
  pcall(function()
    ctx.storage:write('state.txt', 'bank=' .. S.bank .. '\nidx=' .. S.idx .. '\ngivens=' .. S.givens ..
      '\ncells=' .. S.cells .. '\nsel=' .. (S.sel or 0) .. '\ncheck=' .. tostring(S.check))
  end)
end

local function read_saved()
  local ok, s = pcall(function() return ctx.storage:read('state.txt') end)
  if not ok or type(s) ~= 'string' then return nil end
  local t = {}
  for k, v in s:gmatch('([%w_]+)=([^\n]*)') do t[k] = v end
  if not t.givens then return nil end
  return { bank = t.bank, idx = math.tointeger(tonumber(t.idx)), givens = t.givens, cells = t.cells,
           sel = math.tointeger(tonumber(t.sel)), check = t.check ~= 'false' }
end

------------------------------------------------------------------ drawing

local G                 -- the graphics of the running on_draw

local function font(name) return ctx.fonts and ctx.fonts[name] end
local function line_h(name)
  local ok, h = pcall(function() return font(name).line_height end)
  return (ok and tonumber(h)) or (name == 'large' and 30 or name == 'small' and 20 or 24)
end
local function text_w(s, f)
  local ok, w = pcall(function() return f:measure(s) end)
  if ok and type(w) == 'number' and w > 0 then return w end
  return 13 * #s
end
local function ctext(cx, cy, s, name)
  name = name or 'medium'
  local f = font(name)
  G:text(cx - text_w(s, f) // 2, cy - line_h(name) // 2, s, { font = f })
end
local function rtext(right, y, s, name)
  local f = font(name or 'medium')
  G:text(right - text_w(s, f), y, s, { font = f })
end
local function bar(x, y, w, h) G:rect(x, y, w, h, { fill = true }) end

local function draw_grid()
  for k = 0, 9 do
    local v = k * CELL
    if k % 3 == 0 then
      bar(GX + v - 2, GY - 2, 4, 9 * CELL + 4); bar(GX - 2, GY + v - 2, 9 * CELL + 4, 4)
    else
      bar(GX + v - 1, GY, 2, 9 * CELL); bar(GX, GY + v - 1, 9 * CELL, 2)
    end
  end
  local bad = S.check and conflicts(S.cells) or {}
  for r = 0, 8 do
    for c = 0, 8 do
      local i = cell_index(r, c)
      local x, y = GX + c * CELL, GY + r * CELL
      local d = S.cells:sub(i, i)
      if i == S.sel then G:rect(x + 4, y + 4, CELL - 8, CELL - 8, { line_width = 3 }) end
      if d ~= '0' then
        ctext(x + CELL // 2, y + CELL // 2, d, 'large')
        if S.givens:sub(i, i) == '0' then bar(x + 17, y + 41, 16, 2) end      -- entered, not given
        if bad[i] then
          for o = 0, 2 do G:line(x + 34 + o, y + 5, x + 45 + o, y + 16); G:line(x + 45 + o, y + 5, x + 34 + o, y + 16) end
        end
      end
    end
  end
end

local function act_label(id)
  if id == 'erase' then return 'Erase' end
  if id == 'check' then return S.check and 'Chk on' or 'Chk off' end
  if id == 'next' then return 'Next' end
  return 'Bank'
end

function on_draw(c, gg)
  G = gg or rawget(_G, 'g')
  if not G then return end
  G:clear(0)
  local bank = bank_by_name(S.bank)
  G:text(GX, 18, 'Sudoku', { font = font('large') })
  rtext(480 - GX, 24, bank.label .. '  ' .. S.idx .. '/' .. bank.count)
  bar(GX, 70, 480 - 2 * GX, 2)
  draw_grid()
  for d = 1, 9 do
    local x = PAD_X + (d - 1) * (PAD_W + PAD_GAP)
    G:rect(x, PAD_Y, PAD_W, PAD_H, { line_width = 2 })
    ctext(x + PAD_W // 2, PAD_Y + PAD_H // 2, tostring(d), 'large')
  end
  for k, id in ipairs(ACTS) do
    local x = ACT_X + (k - 1) * (ACT_W + ACT_GAP)
    G:rect(x, ACT_Y, ACT_W, ACT_H, { line_width = 2 })
    ctext(x + ACT_W // 2, ACT_Y + ACT_H // 2, act_label(id))
  end
  if msg then ctext(240, 730, msg)
  elseif not data_ok then ctext(240, 730, 'built-in bank (no data section)') end
  bar(GX, 752, 480 - 2 * GX, 2)
  ctext(240, 776, 'tap a cell, then a digit', 'small')
end

------------------------------------------------------------------ input and lifecycle

local function tap(x, y)
  if x >= GX and x < GX + 9 * CELL and y >= GY and y < GY + 9 * CELL then
    S.sel = cell_index((y - GY) // CELL, (x - GX) // CELL)
    msg = nil
    return
  end
  if y >= PAD_Y and y < PAD_Y + PAD_H then
    local k = (x - PAD_X) // (PAD_W + PAD_GAP)
    if k >= 0 and k < 9 and x - PAD_X - k * (PAD_W + PAD_GAP) < PAD_W then
      if S.sel then set_cell(S.sel, tostring(k + 1)) else msg = 'tap a cell first' end
    end
    return
  end
  if y >= ACT_Y and y < ACT_Y + ACT_H then
    local k = (x - ACT_X) // (ACT_W + ACT_GAP)
    if k < 0 or k > 3 or x - ACT_X - k * (ACT_W + ACT_GAP) >= ACT_W then return end
    local id = ACTS[k + 1]
    if id == 'erase' then if S.sel then set_cell(S.sel, '0') end
    elseif id == 'check' then S.check = not S.check
    elseif id == 'next' then step_puzzle(1)
    elseif id == 'bank' then next_bank() end
  end
end

-- side buttons send more than one event per press: keep the press, once
local last_key, last_key_ms = nil, nil
local function key_accepted(ev)
  local ph = ev.phase or ev.action or ev.state
  if ph == 'up' or ph == 'release' or ph == 'released' or ev.pressed == false or ev.down == false then return false end
  local okm, now = pcall(function() return ctx.clock:millis() end)
  local t = tonumber(ev.time_ms) or (okm and tonumber(now)) or nil
  if t and last_key == ev.key and last_key_ms and t - last_key_ms >= 0 and t - last_key_ms < 250 then return false end
  last_key, last_key_ms = ev.key, t
  return true
end

function on_input(_, ev)
  if type(ev) ~= 'table' then return false end
  if ev.type == 'key' then
    if not key_accepted(ev) then return true end
    if ev.key == 'up' or ev.key == 'left' then step_puzzle(-1) elseif ev.key == 'down' or ev.key == 'right' then step_puzzle(1) end
  elseif (ev.type == 'pointer' and ev.phase == 'up' and (ev.gesture == nil or ev.gesture == 'tap'))
      or (ev.type == 'touch' and ev.gesture == 'tap') then
    tap(ev.x or 0, ev.y or 0)
  else
    return true
  end
  save_state()
  pcall(function() ctx.invalidate() end)
  return true
end

function on_load(c)
  c = c or ctx
  if type(c.state) ~= 'table' then c.state = {} end
  load_banks()
  local saved = read_saved()
  if saved then for k, v in pairs(saved) do c.state[k] = v end end
  adopt_state(c.state)
end

function on_leave() save_state() end

