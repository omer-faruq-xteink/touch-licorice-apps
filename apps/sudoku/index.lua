-- Sudoku for XTOS Licorice mini apps (Lua API 0.8, 480 x 800 portrait, 1 bpp).
--
-- Rules as in CPR-vCodex's Sudoku: a 9x9 grid, givens are fixed, "solved" means every cell is filled
-- and no digit repeats in a row, column or 3x3 box (the banks have unique solutions, so that is the
-- solution). Optional mistake marking shows the cells that break a rule right now.
--
-- Puzzle banks: the package's DATA section (xtpack.py packs sudoku/data/*.txt and writes banks.tsv:
-- "file<TAB>count<TAB>stride<TAB>label"). Each bank file has one puzzle per line with a uniform line
-- length, so puzzle N is read with reader:seek((N - 1) * stride) + read_line(). Three line formats
-- are recognised, as downloaded: sudoku-exchange "<id> <81 digits> <rating>", line81 "<81 chars>",
-- Kaggle CSV "<81 digits>,<81 digits>". When the data section is missing or unreadable the app uses
-- the small bank embedded below.
--
-- Controls: tap a cell, then a digit on the pad; Erase clears; Chk toggles mistake marking; Next /
-- Bank move on; the side buttons go to the previous / next puzzle. Progress lives in ctx.state.

