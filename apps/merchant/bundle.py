"""Bundle Merchant into one index.lua for the device.

  python apps/merchant/bundle.py

The game rules, themes and translations come unchanged from merchant.koplugin (src/merchant_game.lua,
src/merchant_themes.lua, src/merchant_l10n/*.lua; upstream commit noted in README). The device's
Lua host has no `require` for package files, so each one becomes a function in a small module
table, behind a local `require` that also answers the two KOReader names they use:
"ffi/util" (template) and "merchant_l10n" (the translation lookup, here driven by the app's
language setting). src/ui.lua, the device screen, comes last. build_all.py runs this first.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')

PRELUDE = r"""-- GENERATED by apps/merchant/bundle.py from src/ -- edit those files, not this one.
-- Merchant for XTOS Licorice: the merchant.koplugin game (rules, themes, translations) with a
-- device screen (src/ui.lua). Every ctx.* function is a method on this API: colon calls.

-- the game seeds its dice from os.time(); the host may not offer os
local os = { time = function()
  local ok, t = pcall(function() return ctx.clock:millis() end)
  return (ok and tonumber(t)) or 0
end }

local __mods, __loaded = {}, {}
local function require(name)
  local v = __loaded[name]
  if v ~= nil then return v end
  local f = __mods[name]
  if not f then error('module not found: ' .. tostring(name)) end
  v = f()
  if v == nil then v = true end
  __loaded[name] = v
  return v
end
-- forget loaded modules whose name starts with prefix (a language change reloads them)
local function __unload(prefix)
  for k in pairs(__loaded) do
    if k:sub(1, #prefix) == prefix and k ~= 'merchant_l10n' then __loaded[k] = nil end
  end
end

__mods['ffi/util'] = function()
  -- KOReader's template: %1 .. %9 replaced by the arguments
  return { template = function(fmt, ...)
    local a = table.pack(...)
    return (tostring(fmt):gsub('%%(%d)', function(n)
      local v = a[tonumber(n)]
      if v == nil then return '%' .. n end
      return tostring(v)
    end))
  end }
end

__mods['merchant_l10n'] = function()
  -- _("English") -> the chosen language's string, or the English one
  local M = { lang = 'en', dict = {} }
  function M.set(lang)
    M.lang = lang or 'en'
    M.dict = {}
    if M.lang ~= 'en' then
      local ok, t = pcall(require, 'merchant_l10n/' .. M.lang)
      if ok and type(t) == 'table' then M.dict = t end
    end
  end
  return setmetatable(M, { __call = function(self, s)
    local v = self.dict[s]
    if v ~= nil then return v end
    return s
  end })
end
"""


def module(name, path):
    body = open(path, encoding='utf-8').read().rstrip('\n')
    return f"\n__mods['{name}'] = function()\n{body}\nend\n"


def bundle():
    parts = [PRELUDE]
    ldir = os.path.join(SRC, 'merchant_l10n')
    for fn in sorted(os.listdir(ldir)):
        if fn.endswith('.lua'):
            parts.append(module('merchant_l10n/' + fn[:-4], os.path.join(ldir, fn)))
    parts.append(module('merchant_themes', os.path.join(SRC, 'merchant_themes.lua')))
    parts.append(module('merchant_game', os.path.join(SRC, 'merchant_game.lua')))
    parts.append('\n' + open(os.path.join(SRC, 'ui.lua'), encoding='utf-8').read())
    out = os.path.join(HERE, 'index.lua')
    text = ''.join(parts)
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'merchant: index.lua {len(text)} B ({"updated" if text != old else "unchanged"})')
    return out


if __name__ == '__main__':
    bundle()
