"""Bundle Slide Puzzle into one index.lua for the device.

  python apps/slidepuzzle/bundle.py

The game rules and the translations come unchanged from slidepuzzle.koplugin
(src/slidepuzzle_game.lua, src/slidepuzzle_i18n.lua; upstream commit noted in README). The device's
Lua host has no `require` for package files, so each one becomes a function in a small module
table, behind a local `require` that also answers "ffi/util" (KOReader's template). src/ui.lua,
the device screen, comes last. build_all.py runs this first.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src')

PRELUDE = r"""-- GENERATED by apps/slidepuzzle/bundle.py from src/ -- edit those files, not this one.
-- Slide Puzzle for XTOS Licorice: the slidepuzzle.koplugin game (rules, translations) with a
-- device screen (src/ui.lua). Every ctx.* function is a method on this API: colon calls.

local __mods, __loaded = {}, {}
local function require(name)
  local v = __loaded[name]
  if v ~= nil then return v end
  local f = __mods[name]
  if not f then error('module not found: ' .. tostring(name)) end
  v = f()
  if v == nil then v = true end
  __loaded[name] = v
  return v
end

__mods['ffi/util'] = function()
  -- KOReader's template: %1 .. %9 replaced by the arguments
  return { template = function(fmt, ...)
    local a = table.pack(...)
    return (tostring(fmt):gsub('%%(%d)', function(n)
      local v = a[tonumber(n)]
      if v == nil then return '%' .. n end
      return tostring(v)
    end))
  end }
end
"""


def module(name, path):
    body = open(path, encoding='utf-8').read().rstrip('\n')
    return f"\n__mods['{name}'] = function()\n{body}\nend\n"


def bundle():
    parts = [PRELUDE,
             module('slidepuzzle_i18n', os.path.join(SRC, 'slidepuzzle_i18n.lua')),
             module('slidepuzzle_game', os.path.join(SRC, 'slidepuzzle_game.lua')),
             '\n' + open(os.path.join(SRC, 'ui.lua'), encoding='utf-8').read()]
    out = os.path.join(HERE, 'index.lua')
    text = ''.join(parts)
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'slidepuzzle: index.lua {len(text)} B ({"updated" if text != old else "unchanged"})')
    return out


if __name__ == '__main__':
    bundle()
