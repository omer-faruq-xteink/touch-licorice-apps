"""Bundle Hacker News into index.lua (tools/gamekit/gamekit.lua + src/hn.lua + src/main.lua) and
lockscreen.lua (gamekit as `kit` + src/hn.lua as `N` + src/lock/lock.lua: a lock entry loads alone,
without the app).

  python apps/hackernews/bundle.py
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT_DIR = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'tools', 'gamekit')
sys.path.insert(0, KIT_DIR)
import bundle  # noqa: E402


def bundle_lock():
    kit = open(os.path.join(KIT_DIR, 'gamekit.lua'), encoding='utf-8').read().rstrip('\n')
    hn = open(os.path.join(HERE, 'src', 'hn.lua'), encoding='utf-8').read().rstrip('\n')
    lock = open(os.path.join(HERE, 'src', 'lock', 'lock.lua'), encoding='utf-8').read()
    text = ('-- GENERATED by apps/hackernews/bundle.py from tools/gamekit/gamekit.lua, src/hn.lua and src/lock/lock.lua'
            ' -- edit those files, not this one.\n'
            'local kit = (function()\n' + kit + '\nend)()\n\n'
            'local N = (function()\n' + hn + '\nend)()\n\n' + lock)
    out = os.path.join(HERE, 'lockscreen.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'hackernews: lockscreen.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle.bundle(HERE, shared=('ai',))
    bundle_lock()
