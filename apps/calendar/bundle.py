"""Bundle Calendar: index.lua (tools/gamekit/gamekit.lua + src/cal.lua + src/views.lua + src/main.lua)
and lockscreen.lua (src/cal.lua and src/views.lua as modules + src/lock/lock.lua: a lock entry
loads alone, without the app).

  python apps/calendar/bundle.py
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(HERE)), 'tools', 'gamekit'))
import bundle  # noqa: E402

REQUIRE = """
local __mods, __loaded = {}, {}
local function require(n)
  local v = __loaded[n]
  if v ~= nil then return v end
  v = __mods[n]()
  __loaded[n] = v
  return v
end
"""


def bundle_lock():
    src = os.path.join(HERE, 'src')
    parts = ['-- GENERATED by apps/calendar/bundle.py from src/cal.lua, src/views.lua and src/lock/lock.lua'
             ' -- edit those files, not this one.\n', REQUIRE]
    for name in ('cal', 'views'):
        body = open(os.path.join(src, name + '.lua'), encoding='utf-8').read().rstrip('\n')
        parts.append(f"\n__mods['{name}'] = function()\n{body}\nend\n")
    parts.append('\n' + open(os.path.join(src, 'lock', 'lock.lua'), encoding='utf-8').read())
    text = ''.join(parts)
    out = os.path.join(HERE, 'lockscreen.lua')
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if text != old:
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'calendar: lockscreen.lua {len(text)} B ({"updated" if text != old else "unchanged"})')


if __name__ == '__main__':
    bundle.bundle(HERE)
    bundle_lock()
